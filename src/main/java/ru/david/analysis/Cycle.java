package ru.david.analysis;

import java.util.List;

/**
 * Элементарный цикл графа: замкнутый путь, в котором ни одна вершина не повторяется
 * (петля A->A тоже цикл, из одной дуги).
 *
 * @param path           коды вершин в порядке обхода; первая вершина в конце не повторяется
 *                       и всегда имеет наименьший номер среди вершин цикла
 * @param weightProduct  произведение весов дуг цикла. Это колонка «Показатель» в таблице
 *                       (предположение, на слайде подпись обрезана; см. CLAUDE.md)
 * @param negativeEdges  число дуг с отрицательным весом
 */
public record Cycle(List<String> path, double weightProduct, int negativeEdges) {

    /**
     * Знак цикла равен произведению знаков его дуг, поэтому важна только чётность числа
     * отрицательных дуг: чётное (или ноль) даёт «+», то есть положительную обратную связь,
     * нечётное даёт «-», то есть отрицательную.
     */
    public boolean isPositive() {
        return negativeEdges % 2 == 0;
    }

    /** Путь в виде A->B->C->A: замыкающая дуга возвращает в первую вершину. */
    public String pathText() {
        return String.join("->", path) + "->" + path.get(0);
    }
}
